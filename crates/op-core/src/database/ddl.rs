//! Deterministic DDL. PostgreSQL/MySQL foreign keys follow all tables and indexes,
//! so cycles work without disabling constraint checks. SQLite keeps them inline.
use super::*;

pub fn quote_identifier(name: &str, dialect: Dialect) -> String {
    let delimiter = if dialect == Dialect::MySql { '`' } else { '"' };
    format!(
        "{delimiter}{}{delimiter}",
        name.replace(delimiter, &format!("{delimiter}{delimiter}"))
    )
}
fn text_literal(text: &str, dialect: Dialect) -> String {
    if dialect == Dialect::MySql && text.contains('\\') {
        let hex = text.as_bytes().iter().map(|b| format!("{b:02x}")).collect::<String>();
        return format!("(_utf8mb4 X'{hex}')");
    }
    if dialect == Dialect::PostgreSql && text.contains('\\') {
        return format!("E'{}'", text.replace('\\', "\\\\").replace('\'', "''"));
    }
    format!("'{}'", text.replace('\'', "''"))
}
fn default_sql(value: &DefaultValue, dialect: Dialect) -> Option<String> {
    match value {
        DefaultValue::None => None,
        DefaultValue::Null => Some("NULL".into()),
        DefaultValue::Text(s) => Some(text_literal(s, dialect)),
        DefaultValue::Number(s) => Some(s.trim().into()),
        DefaultValue::Boolean(v) => Some(if *v { "TRUE" } else { "FALSE" }.into()),
        DefaultValue::CurrentDate => Some("CURRENT_DATE".into()),
        DefaultValue::CurrentTimestamp => Some("CURRENT_TIMESTAMP".into()),
    }
}
fn columns(t: &Table, ids: &[Id], d: Dialect) -> String {
    ids.iter()
        .map(|id| quote_identifier(&t.column(*id).expect("validated column").name, d))
        .collect::<Vec<_>>()
        .join(", ")
}
fn foreign_key(s: &Schema, f: &ForeignKey, d: Dialect) -> String {
    let child = s.table(f.table).unwrap();
    let parent = s.table(f.referenced_table).unwrap();
    format!(
        "CONSTRAINT {} FOREIGN KEY ({}) REFERENCES {} ({}) ON DELETE {} ON UPDATE {}",
        quote_identifier(&f.name, d),
        columns(child, &f.columns, d),
        quote_identifier(&parent.name, d),
        columns(parent, &f.referenced_columns, d),
        f.on_delete.sql(),
        f.on_update.sql()
    )
}
pub fn generate(schema: &Schema, dialect: Dialect) -> Result<String, Vec<Diagnostic>> {
    let issues = schema.validate(dialect);
    if !issues.is_empty() {
        return Err(issues);
    }
    let mut out = format!("-- Open Process | {}\n", dialect.label());
    if dialect == Dialect::Sqlite {
        out.push_str("PRAGMA foreign_keys = ON;\n\nBEGIN TRANSACTION;\n\n");
    } else if dialect == Dialect::PostgreSql {
        out.push_str("BEGIN;\n\n");
    }
    for t in &schema.tables {
        let pk = t.primary_key();
        let inline_pk = dialect == Dialect::Sqlite && t.columns.iter().any(|c| c.auto_increment);
        let mut definitions = vec![];
        for c in &t.columns {
            let mut sql = format!("{} {}", quote_identifier(&c.name, dialect), c.data_type.ddl(dialect));
            if c.auto_increment {
                sql.push_str(match dialect {
                    Dialect::PostgreSql => " GENERATED BY DEFAULT AS IDENTITY",
                    Dialect::MySql => " AUTO_INCREMENT",
                    Dialect::Sqlite => " PRIMARY KEY AUTOINCREMENT",
                });
                if dialect == Dialect::PostgreSql {
                    sql.push_str(&format!(" (SEQUENCE NAME {})", quote_identifier(&format!("seq_{}", c.id), dialect)));
                }
            }
            if !c.nullable || c.primary_key {
                sql.push_str(" NOT NULL");
            }
            if let Some(value) = default_sql(&c.default, dialect) {
                sql.push_str(" DEFAULT ");
                if dialect == Dialect::MySql && matches!(c.data_type, SqlType::Text)
                    || dialect == Dialect::MySql && matches!(c.default, DefaultValue::CurrentDate)
                {
                    sql.push_str(&format!("({value})"));
                } else {
                    sql.push_str(&value);
                }
            }
            definitions.push(sql);
        }
        if !pk.is_empty() && !inline_pk {
            definitions.push(format!(
                "CONSTRAINT {} PRIMARY KEY ({})",
                quote_identifier(&format!("pk_{}", t.id), dialect),
                columns(t, &pk, dialect)
            ));
        }
        for c in t.columns.iter().filter(|c| c.unique) {
            definitions.push(format!(
                "CONSTRAINT {} UNIQUE ({})",
                quote_identifier(&format!("uq_{}", c.id), dialect),
                quote_identifier(&c.name, dialect)
            ));
        }
        if dialect == Dialect::Sqlite {
            definitions.extend(
                schema
                    .foreign_keys
                    .iter()
                    .filter(|f| f.table == t.id)
                    .map(|f| foreign_key(schema, f, dialect)),
            );
        }
        out.push_str(&format!(
            "CREATE TABLE {} (\n  {}\n){};\n\n",
            quote_identifier(&t.name, dialect),
            definitions.join(",\n  "),
            if dialect == Dialect::MySql {
                " ENGINE=InnoDB DEFAULT CHARSET=utf8mb4"
            } else {
                ""
            }
        ));
    }
    for t in &schema.tables {
        for i in &t.indexes {
            out.push_str(&format!(
                "CREATE {}INDEX {} ON {} ({});\n",
                if i.unique { "UNIQUE " } else { "" },
                quote_identifier(&i.name, dialect),
                quote_identifier(&t.name, dialect),
                columns(t, &i.columns, dialect)
            ));
        }
    }
    if dialect != Dialect::Sqlite {
        for f in &schema.foreign_keys {
            out.push_str(&format!(
                "ALTER TABLE {} ADD {};\n",
                quote_identifier(&schema.table(f.table).unwrap().name, dialect),
                foreign_key(schema, f, dialect)
            ));
        }
    }
    if dialect != Dialect::MySql {
        out.push_str("\nCOMMIT;\n");
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn exact_decimal_defaults_and_engine_namespaces_are_checked() {
        let mut s = example();
        for value in ["9999999999.99", "-9999999999.99", "123e-2", "1.2300"] {
            s.tables[1].columns[1].default = DefaultValue::Number(value.into());
            assert!(generate(&s, Dialect::PostgreSql).is_ok(), "{value}");
        }
        for value in ["10000000000", "9999999999.999", "1e-3"] {
            s.tables[1].columns[1].default = DefaultValue::Number(value.into());
            assert!(generate(&s, Dialect::PostgreSql).is_err(), "{value}");
        }
        let mut s = example();
        let id = s.add_index(s.tables[0].id).unwrap();
        s.tables[0].indexes.iter_mut().find(|i| i.id == id).unwrap().name = format!("pk_{}", s.tables[0].id);
        assert!(generate(&s, Dialect::PostgreSql).is_err());
        let mut s = example();
        s.tables[0].name = "sqlite_internal".into();
        assert!(generate(&s, Dialect::Sqlite).is_err());
    }
    #[test]
    fn dialects_generate_validated_keys_and_identity_syntax() {
        let s = example();
        for d in Dialect::ALL {
            assert!(s.validate(d).is_empty(), "{d:?}: {:?}", s.validate(d));
            let sql = generate(&s, d).unwrap();
            assert_eq!(sql.matches("CREATE TABLE").count(), 3);
            assert_eq!(sql.matches("FOREIGN KEY").count(), 2);
            assert!(sql.contains("CASCADE"));
        }
        assert!(
            generate(&s, Dialect::PostgreSql)
                .unwrap()
                .contains("GENERATED BY DEFAULT AS IDENTITY")
        );
        assert!(generate(&s, Dialect::MySql).unwrap().contains("AUTO_INCREMENT"));
        let sqlite = generate(&s, Dialect::Sqlite).unwrap();
        assert!(sqlite.contains("INTEGER PRIMARY KEY AUTOINCREMENT"));
        assert!(!sqlite.contains("ALTER TABLE"));
    }
    #[test]
    fn composite_keys_unique_indexes_and_cycles_are_supported() {
        let mut s = Schema::new("composite");
        let a = s.add_table(Pos::default());
        let b = s.add_table(Pos::new(400.0, 0.0));
        for t in &mut s.tables {
            t.columns[0].auto_increment = false;
        }
        let c = s.add_column(a).unwrap();
        let c = s.tables[0].columns.iter_mut().find(|x| x.id == c).unwrap();
        c.primary_key = true;
        c.nullable = false;
        c.data_type = SqlType::Integer;
        s.add_foreign_key(b, a).unwrap();
        s.add_foreign_key(a, b).unwrap();
        for d in Dialect::ALL {
            assert!(generate(&s, d).is_ok(), "{:?}", s.validate(d));
        }
        let index = s.add_index(b).unwrap();
        s.tables[1].indexes.iter_mut().find(|i| i.id == index).unwrap().unique = true;
        assert!(generate(&s, Dialect::Sqlite).unwrap().contains("CREATE UNIQUE INDEX"));
    }
    #[test]
    fn invalid_references_defaults_and_nullable_keys_block_export() {
        let mut s = example();
        s.foreign_keys[0].referenced_columns = vec![s.tables[0].columns[1].id];
        assert!(generate(&s, Dialect::PostgreSql).is_err());
        let mut s = example();
        s.tables[0].columns[0].nullable = true;
        assert!(generate(&s, Dialect::Sqlite).is_err());
        let mut s = example();
        s.tables[1].columns[1].default = DefaultValue::Number("0); DROP TABLE users;--".into());
        assert!(generate(&s, Dialect::MySql).is_err());
        let mut s = example();
        s.tables[0].columns[0].id = s.tables[0].id;
        assert!(s.check_storage().is_err());
        let mut s = example();
        s.foreign_keys[0].on_delete = ReferentialAction::SetNull;
        let id = s.foreign_keys[0].columns[0];
        s.tables[1].columns.iter_mut().find(|c| c.id == id).unwrap().nullable = false;
        assert!(generate(&s, Dialect::Sqlite).is_err());
    }
    #[test]
    fn quotes_defaults_deletion_and_json_roundtrip_preserve_identity() {
        let mut s = example();
        s.tables[0].name = "select \" a`b".into();
        s.tables[0].columns[1].default = DefaultValue::Text("O'Brien\\path".into());
        let pg = generate(&s, Dialect::PostgreSql).unwrap();
        assert!(pg.contains("\"select \"\" a`b\""));
        assert!(pg.contains("E'O''Brien\\\\path'"));
        let my = generate(&s, Dialect::MySql).unwrap();
        assert!(my.contains("`select \" a``b`"));
        assert!(my.contains("_utf8mb4 X'"));
        assert_eq!(serde_json::from_str::<Schema>(&serde_json::to_string(&s).unwrap()).unwrap(), s);
        let parent = s.tables[0].id;
        s.delete_table(parent);
        assert_eq!(s.foreign_keys.len(), 1);
        let fk = s.foreign_keys[0].clone();
        s.delete_column(fk.table, fk.columns[0]);
        assert!(s.foreign_keys.is_empty());
    }
}
