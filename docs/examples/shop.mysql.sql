CREATE TABLE `customers` (
  `id` INTEGER AUTO_INCREMENT NOT NULL,
  `email` VARCHAR(200) NOT NULL,
  CONSTRAINT `pk_1` PRIMARY KEY (`id`),
  CONSTRAINT `uq_3` UNIQUE (`email`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE `orders` (
  `id` INTEGER AUTO_INCREMENT NOT NULL,
  `total` DECIMAL(12,2) NOT NULL DEFAULT 0,
  `customers_id` INTEGER,
  CONSTRAINT `pk_4` PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE `order_items` (
  `id` INTEGER AUTO_INCREMENT NOT NULL,
  `quantity` INTEGER NOT NULL DEFAULT 1,
  `orders_id` INTEGER,
  CONSTRAINT `pk_9` PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

ALTER TABLE `orders` ADD CONSTRAINT `fk_8` FOREIGN KEY (`customers_id`) REFERENCES `customers` (`id`) ON DELETE NO ACTION ON UPDATE NO ACTION;
