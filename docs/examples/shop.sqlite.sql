-- Open Process | SQLite
PRAGMA foreign_keys = ON;

BEGIN TRANSACTION;

CREATE TABLE "customers" (
  "id" INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL,
  "email" VARCHAR(200) NOT NULL,
  CONSTRAINT "uq_3" UNIQUE ("email")
);

CREATE TABLE "orders" (
  "id" INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL,
  "total" DECIMAL(12,2) NOT NULL DEFAULT 0,
  "customers_id" INTEGER,
  CONSTRAINT "fk_8" FOREIGN KEY ("customers_id") REFERENCES "customers" ("id") ON DELETE NO ACTION ON UPDATE NO ACTION
);

CREATE TABLE "order_items" (
  "id" INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL,
  "quantity" INTEGER NOT NULL DEFAULT 1,
  "orders_id" INTEGER,
  CONSTRAINT "fk_13" FOREIGN KEY ("orders_id") REFERENCES "orders" ("id") ON DELETE CASCADE ON UPDATE NO ACTION
);


COMMIT;
